def _shard(
    *,
    entry_id: int,
    shard_no: str,
    plan_id: str,
    plan_name: str,
    seq: int,
    shard_range: str,
    node: str,
    status: str,
    records: int,
    day: str,
    start: str,
    end: str,
    retry: int = 0,
    empty: bool = False,
) -> dict[str, Any]:
    return {
        "id": entry_id,
        "status": status,
        "pending": status in {"待分配", "执行中"},
        "abnormal": status == "执行失败",
        "分片编号": shard_no,
        "采集计划": plan_name,
        "分片范围": shard_range,
        "分配节点": node,
        "开始时间": start,
        "结束时间": end,
        "重试次数": str(retry),
        "分片状态": status,
        "plan_id": plan_id,
        "分片序号": seq,
        "记录数": records,
        "空分片": empty,
        "完成时间": end if status == "已完成" else "",
        "日期": day,
    }


